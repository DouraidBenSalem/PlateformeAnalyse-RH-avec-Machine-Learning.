def remove_outliers_zscore(df, cols, threshold):
    """
    Supprime les valeurs aberrantes selon la méthode du Z-score.

    Paramètres :
    - df : DataFrame d'origine
    - cols : liste des colonnes à nettoyer
    - threshold : seuil (en écart-types) au-delà duquel une valeur est considérée aberrante
    """
    df_clean = df.copy()

    for col in cols:
        if col in df_clean.columns:
            # Calcul du Z-score absolu (en conservant l’index)
            z_scores = np.abs(stats.zscore(df_clean[col].dropna()))
            z_scores = pd.Series(z_scores, index=df_clean[col].dropna().index)

            # Comptage avant suppression
            before = df_clean.shape[0]

            # Suppression des valeurs aberrantes
            df_clean = df_clean[(z_scores < threshold) | (df_clean[col].isna())]

            # Comptage après suppression
            after = df_clean.shape[0]

            print(f"→ {col} : {before - after} valeurs aberrantes supprimées (Z-score > {threshold})")

    return df_clean


