# ------------------------------------------------------------
# 2️⃣ Fonction de calcul de Cramér’s V
# ------------------------------------------------------------
def cramers_v(x, y):
    """Calcule le coefficient de Cramér’s V entre deux variables qualitatives."""
    confusion_matrix = pd.crosstab(x, y)
    chi2 = chi2_contingency(confusion_matrix, correction=False)[0]
    n = confusion_matrix.sum().sum()
    r, k = confusion_matrix.shape
    return np.sqrt((chi2 / n) / (min(k - 1, r - 1)))

# ------------------------------------------------------------
# 3️⃣ Calcul de la matrice des associations
# ------------------------------------------------------------
cramers_results = pd.DataFrame(index=cat_cols, columns=cat_cols, dtype=float)

for col1 in cat_cols:
    for col2 in cat_cols:
        if col1 == col2:
            cramers_results.loc[col1, col2] = 1.0
        else:
            cramers_results.loc[col1, col2] = cramers_v(data_clean[col1], data_clean[col2])

# ------------------------------------------------------------
# 4️⃣ Visualisation sous forme de heatmap
# ------------------------------------------------------------
plt.figure(figsize=(10,8))
