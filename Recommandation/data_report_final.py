def plot_correlation_circle(pca, features, pc1=0, pc2=1):
    """Trace le cercle de corrélation (relation entre variables et axes principaux)."""
    plt.figure(figsize=(10, 7))
    plt.axhline(0, color='gray', linestyle='--', lw=0.8)
    plt.axvline(0, color='gray', linestyle='--', lw=0.8)

    # Cercle de corrélation
    circle = plt.Circle((0, 0), 1, color='blue', fill=False, linestyle='--')
    plt.gca().add_artist(circle)

    # 🔹 Flèches plus grandes
    for i, (x, y) in enumerate(zip(pca.components_[pc1, :], pca.components_[pc2, :])):
        plt.arrow(0, 0, x, y,
                  color='red',
                  alpha=0.7,
                  width=0.01,        # ➜ plus épais
                  head_width=0.05,   # ➜ pointe plus grande
                  length_includes_head=True)
        plt.text(x * 1.15, y * 1.15, features[i], fontsize=11, fontweight='bold')

    plt.xlabel(f"PC{pc1+1} ({pca.explained_variance_ratio_[pc1]*100:.2f}%)")
    plt.ylabel(f"PC{pc2+1} ({pca.explained_variance_ratio_[pc2]*100:.2f}%)")
    plt.title(f"🎯 Cercle de corrélation (PC{pc1+1} vs PC{pc2+1})")
    plt.xlim(-1.1, 1.1)
    plt.ylim(-1.1, 1.1)
    plt.grid(alpha=0.3)
    plt.show()

